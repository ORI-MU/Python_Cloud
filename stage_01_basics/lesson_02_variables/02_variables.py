# 知识点：
#   变量 = 一个装数据的"盒子"，用 = 赋值
#   数据类型：str（字符串）、int（整数）、float（小数）、bool（布尔）
#   type() 可以查看数据类型
#   示例：
#     name = "Alice"       # 字符串 str
#     age = 25             # 整数 int
#     height = 1.75        # 浮点数 float
#     is_student = True    # 布尔 bool
# ============================================================

